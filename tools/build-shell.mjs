#!/usr/bin/env node
// Generates sw.js with a content-hashed cache version and the precache list of the app shell.
import fs from 'node:fs'; import path from 'node:path'; import crypto from 'node:crypto'; import { fileURLToPath } from 'node:url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const walk = (d) => fs.readdirSync(path.join(ROOT, d), { withFileTypes: true }).flatMap((e) => e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]);
const shell = ['index.html', 'manifest.webmanifest', 'css/app.css', ...walk('js').filter((f) => !f.startsWith('js/vendor/') && f.endsWith('.js')), ...walk('icons')].sort();
const hash = crypto.createHash('sha256'); for (const f of shell) hash.update(f).update(fs.readFileSync(path.join(ROOT, f)));
const version = hash.digest('hex').slice(0, 12);
const tpl = `// GENERATED by tools/build-shell.mjs — do not edit by hand.
// App shell is cached on install (works offline). Vendor files (OCR/barcode) are cached when first used.
// Network requests to other sites (Open Food Facts) are never cached here.
const VERSION = '${version}';
const SHELL = 'nl-shell-' + VERSION;
const RUNTIME = 'nl-runtime-v1';
const FILES = ${JSON.stringify(shell.map((f) => './' + f), null, 0)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(SHELL).then((c) => c.addAll(FILES.concat(['./']).map((f) => new Request(f, { cache: 'reload' }))))
    // Replacing the v2 worker (network-first, no app state) is safe to do immediately
    .then(() => caches.has('nutriledger-static-v1')).then((legacy) => { if (legacy) return self.skipWaiting(); }));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== SHELL && k !== RUNTIME).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('message', (e) => { if (e.data === 'skipWaiting') self.skipWaiting(); });
self.addEventListener('fetch', (e) => {
  const req = e.request; const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== self.location.origin) return;
  const isNav = req.mode === 'navigate';
  e.respondWith((async () => {
    const shell = await caches.open(SHELL);
    const hit = await shell.match(isNav ? './index.html' : req, { ignoreSearch: true });
    if (hit) return hit;
    const rt = await caches.open(RUNTIME);
    const rhit = await rt.match(req);
    if (rhit) return rhit;
    try {
      const res = await fetch(req);
      if (res.ok && url.pathname.includes('/js/vendor/')) rt.put(req, res.clone());
      return res;
    } catch (err) {
      if (isNav) { const idx = await shell.match('./index.html'); if (idx) return idx; }
      throw err;
    }
  })());
});
`;
fs.writeFileSync(path.join(ROOT, 'sw.js'), tpl);
console.log(`sw.js version ${version}, ${shell.length} shell files`);
